func extractMessages(s *Session, maxTurns int) []llm.Message {
	turns := s.Turns
	if len(turns) > maxTurns {
		turns = turns[len(turns)-maxTurns:]
	}

	var b strings.Builder
	for _, t := range turns {
		who := "Клиент"
		switch {
		case t.From == FromAdmin:
			who = "Санжар"
		case t.Role == RoleAssistant:
			who = "Консультант"
		}
		b.WriteString(who + ": " + clip(t.Text, extractTurnLimit) + "\n")
	}

	return []llm.Message{
		{Role: "system", Content: fmt.Sprintf(extractPrompt, knownFacts(s.Lead))},
		{Role: "user", Content: "Переписка:\n" + b.String()},
	}
}
