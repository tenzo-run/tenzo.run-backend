func systemPrompt(s *Session, rules []string, now time.Time) string {
	var b strings.Builder
	b.WriteString(basePrompt)
	if len(rules) > 0 {
		b.WriteString(rulesHeader)
		for _, rule := range rules {
			b.WriteString("- " + rule + "\n")
		}
	}
	b.WriteString("\n\nКОНТЕКСТ ЭТОГО ЧАТА\n")
	if s.Channel == ChannelTelegram {
		b.WriteString("- Человек пишет в Telegram-бот. Его Telegram уже известен Санжару, контакт не проси: Санжар может ответить прямо здесь.\n")
	} else {
		b.WriteString("- Человек пишет в чат на сайте. Язык страницы: " + localeNames[s.Locale] + ".\n")
	}
	if topic := topicOf(s.Page); topic != "" {
		b.WriteString("- Он открыл чат на странице «" + topic + "».\n")
	}
	if s.Profile != "" {
		b.WriteString("- Профиль в Telegram: " + s.Profile + ".\n")
	}
	b.WriteString("- Сейчас в Алматы " + now.In(Almaty).Format("15:04, 02.01.2006") + ".\n")
	b.WriteString("- Приветствие уже показано. Не здоровайся повторно.\n")
	b.WriteString("- Уже известно: " + knownFacts(s.Lead) + ". Не спрашивай повторно то, что известно.")
	if s.newContact {
		b.WriteString("\n- Контакт человек прислал только что, в последнем сообщении: поблагодари и скажи, что Санжар напишет в течение рабочего дня.")
	}
	return b.String()
}

func topicOf(page string) string {
	for _, part := range strings.Split(strings.Trim(page, "/"), "/") {
		if topic, ok := pageTopics[part]; ok {
			return topic
		}
	}
	return ""
}

func knownFacts(l Lead) string {
	value := func(v string) string {
		if v == "" {
			return "пока нет"
		}
		return v
	}
	return "контакт — " + value(l.Contact) + "; имя — " + value(l.Name) + "; задача — " + value(l.Project) +
		"; бюджет — " + value(l.Budget) + "; срок — " + value(l.Deadline)
}

